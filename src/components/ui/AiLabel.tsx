// "AI-generated" — shown wherever text produced by a language model is displayed: chat answers,
// recommendations, and copy the model drafted (until the user edits it). Docs/ai-act-classification.md
// lists every place it appears; keep the two in step.
export function AiLabel({ edited = false, style }: { edited?: boolean; style?: React.CSSProperties }) {
  return (
    <span
      className="ai-label"
      title={edited ? 'Drafted by AI, edited by you' : 'Generated by AI. Review before you use it.'}
      style={{
        display: 'inline-flex',
        alignItems: 'center',
        fontFamily: 'var(--font-mono)',
        fontSize: 9,
        letterSpacing: '0.06em',
        textTransform: 'uppercase',
        color: 'var(--text-3)',
        border: '1px solid var(--border)',
        borderRadius: 3,
        padding: '1px 5px',
        lineHeight: 1.4,
        whiteSpace: 'nowrap',
        ...style,
      }}
    >
      {edited ? 'AI-drafted · edited' : 'AI-generated'}
    </span>
  );
}
