// Software bill of materials → Docs/licenses.md
//   node scripts/sbom.mjs
// Every package in package-lock.json (direct and transitive, runtime and dev), plus the npm packages the
// edge functions import (Deno resolves those at deploy time, so they aren't in the lockfile; their
// licenses are looked up with `npm view`). Copyleft licenses are flagged for counsel.
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';

const lock = JSON.parse(readFileSync('package-lock.json', 'utf8'));
const pkg = JSON.parse(readFileSync('package.json', 'utf8'));
const direct = new Set([...Object.keys(pkg.dependencies ?? {}), ...Object.keys(pkg.devDependencies ?? {})]);

const COPYLEFT = /\b(A?GPL|LGPL|MPL|EPL|EUPL|CDDL|SSPL|OSL|CC-BY-SA)\b/i;
const STRONG = /\b(AGPL|GPL|SSPL)\b/i;            // GPL/AGPL family: counsel must look at these
const flag = (lic) => !lic ? 'UNKNOWN' : STRONG.test(lic) && !/LGPL/i.test(lic) ? 'GPL/AGPL — review' : COPYLEFT.test(lic) ? 'weak copyleft — review' : '';

const rows = [];
for (const [path, info] of Object.entries(lock.packages ?? {})) {
  if (!path) continue;                              // the root project
  const name = info.name ?? path.replace(/^.*node_modules\//, '');
  rows.push({
    name, version: info.version ?? '', license: info.license ?? '',
    scope: info.dev ? 'dev' : 'runtime', direct: direct.has(name) && path === `node_modules/${name}`,
    flag: flag(info.license),
  });
}

// npm: specifiers in edge functions (e.g. import x from 'npm:@anthropic-ai/sdk')
const fnDeps = new Map();
const walk = (dir) => { for (const f of readdirSync(dir)) { const p = join(dir, f); if (statSync(p).isDirectory()) walk(p); else if (p.endsWith('.ts')) {
  for (const m of readFileSync(p, 'utf8').matchAll(/from\s+['"](npm:|https:\/\/esm\.sh\/)(@?[^@'"/]+(?:\/[^@'"/]+)?)(?:@([^'"/]+))?[^'"]*['"]/g)) {
    const name = m[2]; if (!fnDeps.has(name)) fnDeps.set(name, { version: m[3] ?? 'latest', files: new Set() }); fnDeps.get(name).files.add(p.split(/[\\/]/).slice(-2)[0]);
  }
  for (const m of readFileSync(p, 'utf8').matchAll(/from\s+['"]https:\/\/deno\.land\/(std)@([\d.]+)/g)) {
    const name = `deno std (${m[1]})`; if (!fnDeps.has(name)) fnDeps.set(name, { version: m[2], files: new Set(), license: 'MIT' }); fnDeps.get(name).files.add(p.split(/[\\/]/).slice(-2)[0]);
  }
}}};
walk('supabase/functions');
const fnRows = [...fnDeps].map(([name, d]) => {
  let license = d.license ?? '';
  if (!license) { try { license = execFileSync('npm', ['view', name, 'license'], { encoding: 'utf8', shell: true, timeout: 30000 }).trim(); } catch { license = ''; } }
  return { name, version: d.version, license, used_in: [...d.files].sort().join(', '), flag: flag(license) };
});

rows.sort((a, b) => (b.flag ? 1 : 0) - (a.flag ? 1 : 0) || a.name.localeCompare(b.name));
const flagged = [...rows, ...fnRows].filter(r => r.flag);
const byLicense = rows.reduce((m, r) => (m[r.license || 'UNKNOWN'] = (m[r.license || 'UNKNOWN'] || 0) + 1, m), {});
const esc = (s) => String(s).replace(/\|/g, '\\|');

const md = `# Third-party licenses

Generated by \`node scripts/sbom.mjs\` on ${new Date().toISOString().slice(0, 10)} from \`package-lock.json\` and the
edge functions' imports. Regenerate after any dependency change. Not legal advice: flagged rows are for counsel.

## Summary

- Web app packages (direct + transitive): **${rows.length}** (${rows.filter(r => r.scope === 'runtime').length} runtime, ${rows.filter(r => r.scope === 'dev').length} dev-only).
- Edge function packages: **${fnRows.length}**.
- **Flagged: ${flagged.length}** — ${flagged.length ? flagged.map(r => `\`${r.name}\` (${r.license || 'unknown'})`).join(', ') : 'none'}.
- Dev-only packages are build tools: they are not shipped to users, so their licenses do not attach to the product.

| License | Packages |
|---|---|
${Object.entries(byLicense).sort((a, b) => b[1] - a[1]).map(([l, n]) => `| ${esc(l)} | ${n} |`).join('\n')}

## Edge functions (Deno, resolved at deploy)

| Package | Version | License | Used in | Flag |
|---|---|---|---|---|
${fnRows.map(r => `| ${esc(r.name)} | ${esc(r.version)} | ${esc(r.license || 'unknown')} | ${esc(r.used_in)} | ${r.flag} |`).join('\n')}

## Web app (npm)

| Package | Version | License | Scope | Direct | Flag |
|---|---|---|---|---|---|
${rows.map(r => `| ${esc(r.name)} | ${esc(r.version)} | ${esc(r.license || 'unknown')} | ${r.scope} | ${r.direct ? 'yes' : ''} | ${r.flag} |`).join('\n')}
`;
writeFileSync('Docs/licenses.md', md);
console.log(`Docs/licenses.md: ${rows.length} npm + ${fnRows.length} function packages, ${flagged.length} flagged`);
for (const r of flagged) console.log(`  ${r.flag}: ${r.name} ${r.version} (${r.license || 'unknown'})${r.scope ? ' [' + r.scope + ']' : ''}`);
